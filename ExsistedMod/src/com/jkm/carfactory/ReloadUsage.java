package com.jkm.carfactory;

public class ReloadUsage {//about Function Reload
    int IntAdd(int firstInt ,int rareInt){//2 paras
       return firstInt + rareInt;
    }

    double DoubleAdd(double firstDue ,double rareDue){
        return firstDue + rareDue;
    }

    int IntAdd(int firstInt ,int secInt,int finInt){//3 paras
        return firstInt + secInt + finInt;
    }

    double DoubleAdd(double firstDue ,double secDue,double finDue){
        return firstDue + secDue + finDue;
    }
}
